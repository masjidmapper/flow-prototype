#!/usr/bin/env python3
"""Regenerate css/tokens.css from the Mihrab tokens.

Usage: python3 tools/gen-tokens.py [path/to/masjidmapper]   (default ../masjidmapper)
"""
import json, re, sys, pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../masjidmapper")
t = json.loads((root / "design/mihrab/tokens.json").read_text())
out = pathlib.Path(__file__).resolve().parent.parent / "css/tokens.css"

def ref(v):
    return re.sub(r"\{([a-z0-9-]+)\}", r"var(--\1)", v)

def colors(theme):
    return "\n".join(f"  --{c['name']}: {ref(c['value'][theme])};" for c in t["color"]["tokens"])

static = []
for group in ("spacing", "radius", "shadow", "easing", "duration", "size"):
    for x in t[group]["tokens"]:
        static.append(f"  --{x['name']}: {x['value']};")
for g in t["type"]["groups"]:
    for s in g["styles"]:
        static.append(f"  --{s['name']}: {s['fontWeight']} {s['fontSize']}/{s['lineHeight']} var(--font-sans);")
        static.append(f"  --{s['name']}-tracking: {s['letterSpacing']};")

css = f"""/* Generated by tools/gen-tokens.py from masjidmapper design/mihrab/tokens.json
   ({t['meta']['ref']}, synced {t['meta']['synced']}). Do not edit by hand. */
:root {{
  --font-sans: {t['type']['families']['sans']};
{chr(10).join(static)}
{colors('light')}
  color-scheme: light;
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{colors('dark')}
    color-scheme: dark;
  }}
}}
:root[data-theme="dark"] {{
{colors('dark')}
  color-scheme: dark;
}}
"""
out.write_text(css)
print("wrote", out)
